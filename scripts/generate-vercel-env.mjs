#!/usr/bin/env node
/**
 * Generate env/vercel.env from root .env for Vercel bulk import.
 *
 * Usage:
 *   pnpm generate:vercel-env
 *   pnpm generate:vercel-env https://sovereignx-api.up.railway.app
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env');
const examplePath = resolve(root, 'env/vercel.env.example');
const outPath = resolve(root, 'env/vercel.env');

const apiUrl = (process.argv[2] ?? process.env.VERCEL_API_URL ?? '').replace(/\/$/, '');

const PUBLIC_KEYS = [
  'NEXT_PUBLIC_API_URL',
  'NEXT_PUBLIC_MONAD_RPC_URL',
  'NEXT_PUBLIC_CHAIN_ID',
  'NEXT_PUBLIC_SOVX_TOKEN_ADDRESS',
  'NEXT_PUBLIC_IDENTITY_REGISTRY_ADDRESS',
  'NEXT_PUBLIC_COMPLIANCE_ENGINE_ADDRESS',
  'NEXT_PUBLIC_DIVIDEND_DISTRIBUTOR_ADDRESS',
  'NEXT_PUBLIC_CVA_STABLECOIN_ADDRESS',
  'NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY',
  'NEXT_PUBLIC_CLERK_SIGN_IN_URL',
  'NEXT_PUBLIC_CLERK_SIGN_UP_URL',
  'NEXT_PUBLIC_WC_PROJECT_ID',
];

const SERVER_KEYS = ['CLERK_SECRET_KEY'];

function parseEnv(text) {
  const out = {};
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const val = trimmed.slice(eq + 1).trim();
    out[key] = val;
  }
  return out;
}

const source = existsSync(envPath)
  ? parseEnv(readFileSync(envPath, 'utf8'))
  : parseEnv(readFileSync(examplePath, 'utf8'));

const vars = {};
for (const key of PUBLIC_KEYS) {
  const val = source[key];
  if (val) vars[key] = val;
}

for (const key of SERVER_KEYS) {
  const val = source[key];
  if (val) vars[key] = val;
}

if (!vars.NEXT_PUBLIC_CLERK_SIGN_IN_URL) vars.NEXT_PUBLIC_CLERK_SIGN_IN_URL = '/sign-in';
if (!vars.NEXT_PUBLIC_CLERK_SIGN_UP_URL) vars.NEXT_PUBLIC_CLERK_SIGN_UP_URL = '/sign-up';

if (apiUrl) {
  vars.NEXT_PUBLIC_API_URL = apiUrl;
} else if (!vars.NEXT_PUBLIC_API_URL || vars.NEXT_PUBLIC_API_URL.includes('localhost')) {
  vars.NEXT_PUBLIC_API_URL = 'https://YOUR_API_URL';
}

if (!vars.NEXT_PUBLIC_WC_PROJECT_ID) {
  delete vars.NEXT_PUBLIC_WC_PROJECT_ID;
}

const header = `# Generated by pnpm generate:vercel-env — import in Vercel Dashboard
# Settings → Environment Variables → Import .env → Production + Preview + Development
`;

mkdirSync(resolve(root, 'env'), { recursive: true });
writeFileSync(
  outPath,
  header +
    [...PUBLIC_KEYS, ...SERVER_KEYS]
      .filter((k) => vars[k])
      .map((k) => `${k}=${vars[k]}`)
      .join('\n') +
    '\n',
);

console.log(`Wrote ${outPath}`);
console.log('');
console.log('Import steps:');
console.log('  1. Deploy API first (Railway/Render) — copy its public URL');
console.log('  2. Re-run: pnpm generate:vercel-env <API_URL>');
console.log('  3. Vercel → Settings → Environment Variables → Import → env/vercel.env');
console.log('');
if (vars.NEXT_PUBLIC_API_URL.includes('YOUR_API')) {
  console.log('⚠️  NEXT_PUBLIC_API_URL still placeholder — set your API URL before import.');
} else {
  console.log(`✓  NEXT_PUBLIC_API_URL=${vars.NEXT_PUBLIC_API_URL}`);
}
