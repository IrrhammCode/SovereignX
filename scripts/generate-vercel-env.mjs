#!/usr/bin/env node
/**
 * Generate env/vercel.env from root .env for Vercel bulk import.
 *
 * Usage:
 *   pnpm generate:vercel-env              # FREE: same-origin API on Vercel (no NEXT_PUBLIC_API_URL)
 *   pnpm generate:vercel-env --split URL   # Split: external API (Render/Railway)
 *   pnpm generate:vercel-env https://...   # Same as --split
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env');
const examplePath = resolve(root, 'env/vercel.env.example');
const outPath = resolve(root, 'env/vercel.env');

const args = process.argv.slice(2);
const splitFlag = args.indexOf('--split');
const apiUrlArg =
  splitFlag >= 0
    ? args[splitFlag + 1]?.replace(/\/$/, '')
    : args.find((a) => a.startsWith('http'))?.replace(/\/$/, '') ?? '';

const freeMode = !apiUrlArg;

const PUBLIC_KEYS = [
  'NEXT_PUBLIC_API_URL',
  'NEXT_PUBLIC_MONAD_RPC_URL',
  'NEXT_PUBLIC_CHAIN_ID',
  'NEXT_PUBLIC_SOVX_TOKEN_ADDRESS',
  'NEXT_PUBLIC_IDENTITY_REGISTRY_ADDRESS',
  'NEXT_PUBLIC_COMPLIANCE_ENGINE_ADDRESS',
  'NEXT_PUBLIC_DIVIDEND_DISTRIBUTOR_ADDRESS',
  'NEXT_PUBLIC_CVA_STABLECOIN_ADDRESS',
  'NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY',
  'NEXT_PUBLIC_CLERK_SIGN_IN_URL',
  'NEXT_PUBLIC_CLERK_SIGN_UP_URL',
  'NEXT_PUBLIC_WC_PROJECT_ID',
];

const SERVER_KEYS = ['CLERK_SECRET_KEY'];

/** Required on Vercel when API runs embedded (free same-origin deploy) */
const EMBEDDED_API_KEYS = [
  'CLEANVERSE_API_ID',
  'CLEANVERSE_API_KEY',
  'CLEANVERSE_API_URL',
  'CLEANVERSE_SKILLS_URL',
  'MONAD_RPC_URL',
  'MONAD_CHAIN_ID',
  'DEPLOYER_PRIVATE_KEY',
  'SOVX_TOKEN_ADDRESS',
  'IDENTITY_REGISTRY_ADDRESS',
  'COMPLIANCE_ENGINE_ADDRESS',
  'DIVIDEND_DISTRIBUTOR_ADDRESS',
  'CVA_STABLECOIN_ADDRESS',
  'VALIDATOR_POOL_ADDRESS',
  'TRAVEL_RULE_THRESHOLD_USD',
  'FRED_API_KEY',
];

function parseEnv(text) {
  const out = {};
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    out[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim();
  }
  return out;
}

const source = existsSync(envPath)
  ? parseEnv(readFileSync(envPath, 'utf8'))
  : parseEnv(readFileSync(examplePath, 'utf8'));

const vars = {};
for (const key of PUBLIC_KEYS) {
  const val = source[key];
  if (val) vars[key] = val;
}
for (const key of SERVER_KEYS) {
  const val = source[key];
  if (val) vars[key] = val;
}

if (!vars.NEXT_PUBLIC_CLERK_SIGN_IN_URL) vars.NEXT_PUBLIC_CLERK_SIGN_IN_URL = '/sign-in';
if (!vars.NEXT_PUBLIC_CLERK_SIGN_UP_URL) vars.NEXT_PUBLIC_CLERK_SIGN_UP_URL = '/sign-up';

if (freeMode) {
  delete vars.NEXT_PUBLIC_API_URL;
  for (const key of EMBEDDED_API_KEYS) {
    const val = source[key];
    if (val) vars[key] = val;
  }
} else {
  vars.NEXT_PUBLIC_API_URL = apiUrlArg;
}

if (!vars.NEXT_PUBLIC_WC_PROJECT_ID) delete vars.NEXT_PUBLIC_WC_PROJECT_ID;

const header = freeMode
  ? `# Generated by pnpm generate:vercel-env — FREE mode (API on same Vercel project)
# Import: Vercel → Settings → Environment Variables → Import → Production + Preview + Development
# Do NOT set NEXT_PUBLIC_API_URL — frontend uses same-origin /api/*
`
  : `# Generated by pnpm generate:vercel-env --split ${apiUrlArg}
# Import: Vercel → Settings → Environment Variables → Import
`;

const orderedKeys = freeMode
  ? [...PUBLIC_KEYS.filter((k) => k !== 'NEXT_PUBLIC_API_URL'), ...SERVER_KEYS, ...EMBEDDED_API_KEYS]
  : [...PUBLIC_KEYS, ...SERVER_KEYS];

mkdirSync(resolve(root, 'env'), { recursive: true });
writeFileSync(
  outPath,
  header + orderedKeys.filter((k) => vars[k]).map((k) => `${k}=${vars[k]}`).join('\n') + '\n',
);

console.log(`Wrote ${outPath}`);
console.log('');
if (freeMode) {
  console.log('FREE deploy mode — API runs on Vercel at /api/*');
  console.log('Import env/vercel.env into your existing Vercel + Clerk project, then redeploy.');
  console.log('Test: https://YOUR-APP.vercel.app/api/health');
  const missing = EMBEDDED_API_KEYS.filter((k) => !vars[k] && k !== 'FRED_API_KEY');
  if (missing.length) {
    console.log('');
    console.log('⚠️  Missing API secrets in .env:', missing.join(', '));
  }
} else {
  console.log(`Split deploy — NEXT_PUBLIC_API_URL=${apiUrlArg}`);
  console.log('Also deploy API secrets on Render/Railway (pnpm generate:vercel-api-env).');
}
