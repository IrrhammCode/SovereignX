#!/usr/bin/env node
/**
 * Generate env/vercel.api.env from root .env for API host (Railway/Render).
 * Usage: pnpm generate:vercel-api-env [INDEXER_URL]
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env');
const examplePath = resolve(root, 'env/vercel.api.env.example');
const outPath = resolve(root, 'env/vercel.api.env');

const indexerUrl = (process.argv[2] ?? process.env.INDEXER_PUBLIC_URL ?? '').replace(/\/$/, '');

const API_KEYS = [
  'CLEANVERSE_API_ID',
  'CLEANVERSE_API_KEY',
  'CLEANVERSE_API_URL',
  'CLEANVERSE_SKILLS_URL',
  'MONAD_RPC_URL',
  'MONAD_CHAIN_ID',
  'DEPLOYER_PRIVATE_KEY',
  'SOVX_TOKEN_ADDRESS',
  'IDENTITY_REGISTRY_ADDRESS',
  'COMPLIANCE_ENGINE_ADDRESS',
  'DIVIDEND_DISTRIBUTOR_ADDRESS',
  'CVA_STABLECOIN_ADDRESS',
  'API_PORT',
  'AUDIT_LOG_PATH',
  'ORACLE_HISTORY_PATH',
  'VALIDATOR_POOL_ADDRESS',
  'INDEXER_URL',
  'INDEXER_FROM_BLOCK',
  'INDEXER_LOOKBACK_BLOCKS',
  'ALLOWED_ORIGINS',
  'FRED_API_KEY',
];

function parseEnv(text) {
  const out = {};
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    out[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim();
  }
  return out;
}

const source = existsSync(envPath)
  ? parseEnv(readFileSync(envPath, 'utf8'))
  : parseEnv(readFileSync(examplePath, 'utf8'));

const vars = {};
for (const key of API_KEYS) {
  const val = source[key];
  if (val) vars[key] = val;
}

if (indexerUrl) vars.INDEXER_URL = indexerUrl;
else if (!vars.INDEXER_URL || vars.INDEXER_URL.includes('localhost')) {
  vars.INDEXER_URL = 'https://YOUR_INDEXER_URL';
}

vars.API_PORT = vars.API_PORT ?? '4000';

mkdirSync(resolve(root, 'env'), { recursive: true });
writeFileSync(
  outPath,
  `# Generated by pnpm generate:vercel-api-env — import on Railway/Render (NOT Vercel)\n` +
    API_KEYS.filter((k) => vars[k]).map((k) => `${k}=${vars[k]}`).join('\n') +
    '\n',
);

console.log(`Wrote ${outPath}`);
if (vars.INDEXER_URL.includes('YOUR_')) {
  console.log('⚠️  Set INDEXER_URL after deploying indexer, or pass as argument.');
}
